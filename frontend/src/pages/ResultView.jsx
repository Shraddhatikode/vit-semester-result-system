import React from 'react';

const ResultView = ({ resultData, onNavigate }) => {
  if (!resultData) {
    return (
      <section id="result-view" className="view-section active">
        <div className="text-center py-5">
          <h3>No result data selected.</h3>
          <button className="btn btn-primary mt-3" onClick={() => onNavigate('dashboard-view')}>
            Go to Dashboard
          </button>
        </div>
      </section>
    );
  }

  const currentDate = new Date().toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });

  return (
    <section id="result-view" className="view-section active">
      <div className="no-print d-flex justify-content-between align-items-center mb-4">
        <div>
          <h2 className="fw-bold mb-1">Official Semester Grade Sheet</h2>
          <p className="text-muted mb-0">Generated by Backend Calculation Engine</p>
        </div>
        <div className="d-flex gap-2">
          <button
            className="btn btn-outline-secondary nav-trigger"
            onClick={() => onNavigate('dashboard-view')}
          >
            <i className="bi bi-arrow-left"></i> Dashboard
          </button>
          <button className="btn btn-primary" onClick={() => window.print()}>
            <i className="bi bi-printer-fill"></i> Print Result
          </button>
        </div>
      </div>

      {/* Printable Marksheet Container */}
      <div className="marksheet-container">
        <div className="marksheet-watermark">VISHWAKARMA INSTITUTE</div>

        <div className="marksheet-header">
          <div className="d-flex align-items-center justify-content-center gap-3 mb-2">
            <div
              className="vit-badge-logo"
              style={{ width: '54px', height: '54px', fontSize: '1.5rem', background: '#1b365d', color: 'white' }}
            >
              VIT
            </div>
            <div>
              <h2 className="marksheet-title-main">VISHWAKARMA INSTITUTE OF TECHNOLOGY</h2>
              <p className="marksheet-subtitle">
                An Autonomous Institute Affiliated to Savitribai Phule Pune University
              </p>
            </div>
          </div>
          <div className="marksheet-doc-title">SEMESTER PERFORMANCE STATEMENT</div>
        </div>

        {/* Student Metadata Banner */}
        <div className="student-info-grid">
          <div className="row g-3">
            <div className="col-6 col-md-3">
              <div className="info-label">PRN</div>
              <div className="info-val" id="sheet-prn">
                {resultData.prn || '-'}
              </div>
            </div>
            <div className="col-6 col-md-3">
              <div className="info-label">Student Name</div>
              <div className="info-val" id="sheet-name">
                {resultData.name || '-'}
              </div>
            </div>
            <div className="col-6 col-md-3">
              <div className="info-label">Branch</div>
              <div className="info-val" id="sheet-branch">
                {resultData.branch || '-'}
              </div>
            </div>
            <div className="col-6 col-md-3">
              <div className="info-label">Semester</div>
              <div className="info-val" id="sheet-semester">
                {resultData.semester ? `Semester ${resultData.semester}` : '-'}
              </div>
            </div>
          </div>
        </div>

        {/* Result Breakdown Table */}
        <table className="table table-bordered align-middle text-center mb-4">
          <thead className="table-light">
            <tr>
              <th>Subject Code</th>
              <th className="text-start">Subject Name</th>
              <th>Credits</th>
              <th>MSE (/30)</th>
              <th>ESE (/100)</th>
              <th>Final Marks (/100)</th>
              <th>Grade</th>
              <th>Grade Point</th>
            </tr>
          </thead>
          <tbody id="sheet-table-body">
            {resultData.subjectResults && resultData.subjectResults.length > 0 ? (
              resultData.subjectResults.map((sr, idx) => (
                <tr key={idx}>
                  <td className="fw-bold">{sr.subjectCode}</td>
                  <td className="text-start">{sr.subjectName}</td>
                  <td>{sr.credits}</td>
                  <td>{sr.mse.toFixed(1)}</td>
                  <td>{sr.ese.toFixed(1)}</td>
                  <td className="fw-bold">{sr.finalMarks.toFixed(1)}</td>
                  <td>
                    <span className={`badge grade-badge grade-${sr.grade.replace('+', '-plus')}`}>
                      {sr.grade}
                    </span>
                  </td>
                  <td className="fw-bold">{sr.gradePoint}</td>
                </tr>
              ))
            ) : (
              <tr>
                <td colSpan="8" className="text-muted py-3">
                  No subject records found.
                </td>
              </tr>
            )}
          </tbody>
        </table>

        {/* Summary Card */}
        <div className="marksheet-summary-box mb-4">
          <div className="summary-item">
            <div className="num" id="sheet-total-marks">
              {resultData.totalMarks ? `${resultData.totalMarks.toFixed(2)} / 400` : '0 / 400'}
            </div>
            <div className="lbl">Total Marks</div>
          </div>
          <div className="summary-item">
            <div className="num" id="sheet-sgpa">
              {resultData.sgpa ? resultData.sgpa.toFixed(2) : '0.00'}
            </div>
            <div className="lbl">SGPA (out of 10.0)</div>
          </div>
          <div className="summary-item">
            <div
              id="sheet-status-badge"
              className={resultData.resultStatus === 'PASS' ? 'badge-pass' : 'badge-fail'}
              style={{ fontSize: '1.1rem' }}
            >
              {resultData.resultStatus === 'PASS' ? (
                <>
                  <i className="bi bi-check-circle-fill me-1"></i> PASS
                </>
              ) : (
                <>
                  <i className="bi bi-x-circle-fill me-1"></i> FAIL
                </>
              )}
            </div>
            <div className="lbl mt-1">Result Status</div>
          </div>
        </div>

        {/* Official Footer */}
        <div className="d-flex justify-content-between align-items-end pt-3 mt-3 border-top">
          <div className="small text-muted">
            <div>
              Date of Issue: <span id="sheet-date">{currentDate}</span>
            </div>
            <div>Formula: Final Marks = MSE + (ESE × 0.70) | SGPA = Σ(Credit × GP) / Σ Credits</div>
          </div>
          <div className="text-center">
            <div style={{ fontFamily: 'Outfit', fontWeight: 700, color: 'var(--vit-primary)' }}>
              CONTROLLER OF EXAMINATIONS
            </div>
            <div className="small text-muted">VIT Pune Academic Authority</div>
          </div>
        </div>
      </div>
    </section>
  );
};

export default ResultView;
